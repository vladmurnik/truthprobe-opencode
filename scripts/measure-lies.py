#!/usr/bin/env python3
"""Measures whether TruthProbe sees a deliberately wrong answer.

Collecting real hallucinations failed: 1440 requests to four gateway models
produced not a single wrong answer. So the only lie we
are 100% sure about is the one we ordered ourselves: `make-liar-bank.py` asks the
model to answer incorrectly, and the answer is still generated by the model, with its own
real logprobs.

What the script computes:

  geometric   built-in runtime formula (exp(meanLp), see §14 VALIDATION);
              no training at all, exactly what users run today.
  fitted      logistic regression over the same four features, trained
              with honest cross-validation (out-of-fold): the weights never see the rows
              they are validated on.
  variants    fixed formulas without training (`--variants`), the comparison
              exp(meanLp) was chosen from.

    python3 scripts/measure-lies.py data/rows-lie-vs-truth.jsonl
    python3 scripts/measure-lies.py data/rows-lie-vs-truth.jsonl --json

IMPORTANT CAVEAT. A deliberate lie is not the same as a spontaneous
hallucination: a model told to lie "knows" the truth and its first token
depends on the strange instruction rather than on the fact. The numbers below answer the question
"does the scorer see that the model lied on demand", and say nothing about whether
it would catch a confident fabrication in a normal conversation. These are different things, and the latter
is still unmeasured.
"""

from __future__ import annotations

import argparse
import json
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import calibrate  # noqa: E402
import evaluate  # noqa: E402

FOLDS = 5
SEED = 7


def load(path: str) -> list[dict]:
    rows: list[dict] = []
    with open(path, encoding="utf-8") as handle:
        for n, line in enumerate(handle, start=1):
            line = line.strip()
            if not line:
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError:
                print(f"{path}:{n}: not JSON, line skipped", file=sys.stderr)
                continue
            label = row.get("label")
            if label is None and row.get("condition"):
                label = 1 if row["condition"] == "truthful" else 0
            if label is None or "meanLp" not in row:
                continue
            row["label"] = bool(int(label))
            rows.append(row)
    return rows


def geometric(row: dict) -> float:
    """Exactly the geometricScorer formula from packages/core/src/truthprobe/scorer.ts: exp(meanLp)."""
    import math

    mean_lp = float(row["meanLp"])
    return min(1.0, max(0.0, math.exp(mean_lp)))


def variants(row: dict) -> dict[str, float]:
    """Fixed formulas from §14 VALIDATION, so the comparison can be reproduced from the repository."""
    import math

    geo = min(1.0, max(0.0, math.exp(float(row["meanLp"]))))
    worst = min(1.0, max(0.0, math.exp(float(row["minLp"]))))
    phi = min(1.0, max(0.0, float(row.get("phi") or 0.0)))
    frac_low = min(1.0, max(0.0, float(row.get("fracLow") or 0.0)))
    return {
        "old 0.4geo+0.3worst+0.3phi": min(1.0, 0.4 * geo + 0.3 * worst + 0.3 * phi),
        "geo only": geo,
        "worst only": worst,
        "phi only": phi,
        "geo*(1-fracLow)": min(1.0, geo * (1.0 - frac_low)),
    }


def out_of_fold(rows: list[dict]) -> tuple[list[tuple[float, bool]], float | None]:
    """OOF with group splitting by `(model, prompt)`.

    A row-wise split leaked: the same answer sits in the dataset several
    times, and the question is reused by every model, so the test almost entirely
    repeated the training set. Folds are cut by whole groups (`calibrate.fold_assignment`).
    """
    data = rows[:]
    assignment = calibrate.fold_assignment(data, FOLDS)
    pairs: list[tuple[float, bool]] = []
    for fold in range(FOLDS):
        test = [row for row, index in zip(data, assignment) if index == fold]
        train = [row for row, index in zip(data, assignment) if index != fold]
        if not train or not test:
            continue
        weights = calibrate.fit(train)
        for row in test:
            pairs.append((calibrate.predict(weights, row), row["label"]))
    return pairs, None


def report(name: str, pairs: list[tuple[float, bool]]) -> dict:
    positives = sum(1 for _, label in pairs if label)
    negatives = len(pairs) - positives
    auroc = evaluate.auroc(pairs)
    ece = evaluate.ece(pairs, 10)
    brier = evaluate.brier(pairs)
    return {
        "mode": name,
        "rows": len(pairs),
        "positives": positives,
        "negatives": negatives,
        "auroc": auroc,
        "ece": ece,
        "brier": brier,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("rows", help="JSONL: rows with label 0/1 and features meanLp/minLp/phi/fracLow")
    parser.add_argument("--json", action="store_true", help="print a machine-readable report")
    parser.add_argument("--variants", action="store_true", help="compare the fixed formulas from §14 VALIDATION")
    parser.add_argument("--dedupe", action="store_true", help="collapse byte-identical repeats (model,prompt,answer,label)")
    args = parser.parse_args()

    rows = load(args.rows)
    if not rows:
        print("no usable rows", file=sys.stderr)
        return 2

    if args.dedupe:
        seen: set[tuple] = set()
        unique: list[dict] = []
        for row in rows:
            key = (row.get("model"), row.get("prompt"), row.get("answer"), row["label"])
            if key in seen:
                continue
            seen.add(key)
            unique.append(row)
        rows = unique

    unique_rows = len({(row.get("model"), row.get("prompt"), row.get("answer"), row["label"]) for row in rows})
    print(f"== {args.rows}: rows {len(rows)}, unique {unique_rows} (group CV by model+prompt)", file=sys.stderr)

    if args.variants:
        names = list(variants(rows[0]))
        print(f"== {args.rows}: {len(rows)} rows, {len(names)} formulas (no training)")
        print(f"{'formula':30s} {'AUROC':>7s} {'ECE':>6s} {'Brier':>6s}")
        for name in names:
            entry = report(name, [(variants(row)[name], row["label"]) for row in rows])
            auroc = "n/a" if entry["auroc"] is None else f"{entry['auroc']:.3f}"
            print(f"{name:30s} {auroc:>7s} {entry['ece']:6.3f} {entry['brier']:6.3f}")
        return 0

    builtin = report("geometric", [(geometric(row), row["label"]) for row in rows])
    pairs, _ = out_of_fold(rows)
    fitted = report("fitted (out-of-fold)", pairs)

    per_model: list[dict] = []
    for model in sorted({row.get("model") or "?" for row in rows}):
        sub = [row for row in rows if (row.get("model") or "?") == model]
        pos = sum(1 for row in sub if row["label"])
        neg = len(sub) - pos
        if pos < 10 or neg < 30:
            per_model.append({"model": model, "rows": len(sub), "positives": pos, "negatives": neg, "auroc": None})
            continue
        sub_pairs, _ = out_of_fold(sub)
        entry = report("fitted", sub_pairs)
        entry["model"] = model
        entry["positives"] = pos
        entry["negatives"] = neg
        per_model.append(entry)

    if args.json:
        print(json.dumps({"builtin": builtin, "fitted": fitted, "per_model": per_model}, ensure_ascii=False, indent=2))
        return 0

    def fmt(value: float | None, digits: int = 3) -> str:
        return "n/a" if value is None else f"{value:.{digits}f}"

    print(f"== {args.rows}: {len(rows)} rows")
    print(f"{'mode':22s} {'rows':>5s} {'pos':>5s} {'neg':>5s} {'AUROC':>7s} {'ECE':>6s} {'Brier':>6s}")
    for entry in (builtin, fitted):
        print(
            f"{entry['mode']:22s} {entry['rows']:5d} {entry['positives']:5d} {entry['negatives']:5d} "
            f"{fmt(entry['auroc']):>7s} {fmt(entry['ece']):>6s} {fmt(entry['brier']):>6s}"
        )
    print("\nper model (fitted, out-of-fold):")
    for entry in per_model:
        if entry["auroc"] is None:
            print(f"  {entry['model']:26s} n={entry['rows']:3d} pos={entry['positives']:3d} neg={entry['negatives']:3d} — too few negatives")
        else:
            print(
                f"  {entry['model']:26s} n={entry['rows']:3d} pos={entry['positives']:3d} neg={entry['negatives']:3d} "
                f"AUROC {fmt(entry['auroc'])} ECE {fmt(entry['ece'])}"
            )
    print("\nAUROC below 0.5 means the scorer gives false answers MORE confidence than true ones.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
